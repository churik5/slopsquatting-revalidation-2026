"""Erratum draft for the arXiv v2 (revalidation task, item 7).

Turns the recomputed numbers + diff into a concrete list of edits for the
preprint: which numbers change, the §8 limitation about the master-list date, and
the §9.2 correction. Reads reports/recompute.json (must exist).
"""
from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

PUBLISHED_MODEL = {
    "haiku-4-5": (1399, 30303), "sonnet-4-6": (1875, 34633),
    "gemini-2.5-pro": (1983, 34168), "deepseek-v3.2": (1537, 26116),
    "gpt-5.4-mini": (1194, 19589),
}
MODELS = ["haiku-4-5", "sonnet-4-6", "gemini-2.5-pro", "deepseek-v3.2", "gpt-5.4-mini"]


def main():
    res = json.loads((REPO / "reports" / "recompute.json").read_text())
    u = res["universal"]
    today = date.today().isoformat()

    L = [f"# Erratum draft (v2) — generated {today}", "",
         "Prepared from the revalidation run. Numbers are pulled straight from",
         "`reports/recompute.json`; see `reports/diff_published_vs_new.md` for the full diff.", "",
         "## 1. Numbers to change", "",
         "### 1a. Per-model hallucination rates (Table 1 / Figure 2)", "",
         "| Model | old (published) | new (v2) |", "|---|---|---|"]
    for m in MODELS:
        ph, pt = PUBLISHED_MODEL[m]
        old = 100 * ph / pt
        nd = res["per_model"][m]
        L.append(f"| {m} | {old:.2f}% | {nd['rate']:.2f}% [{nd['ci95'][0]:.2f}–{nd['ci95'][1]:.2f}] |")

    L += ["", "### 1b. Universal hallucination set (§9.2, abstract, README)", "",
          f"- Published: **127** (109 PyPI + 18 npm).",
          f"- Corrected: **{u['total']}** ({u['n_pypi']} PyPI + {u['n_npm']} npm), computed on a",
          f"  {today} master-list snapshot with live registry verification.",
          "- The published **109** PyPI figure is not reproducible from the code or notebooks",
          "  (the code yields 120–121 on the original data; see diff report). It must be",
          "  replaced, and the discrepancy acknowledged.",
          "- Every name in the corrected set returns HTTP 404 from the registry at recompute time",
          f"  (names still returning 200: {len(u['any_live_200'])}).", "",
          "### 1c. Aggregate significance stats", "",
          f"- Pairwise χ² significant pairs (Holm): {res['chi2']['n_significant']}/{res['chi2']['n_pairs']}.",
          f"- Permutation test (10 000, seed 42): {res['permutation']['n_significant']}/"
          f"{len(res['permutation']['pairs'])} pairs p<0.05, max p={res['permutation']['max_p']:.4f}.",
          f"- Mean pairwise Jaccard of hallucinated sets: {res['jaccard']['mean']:.3f} "
          f"(range {res['jaccard']['min']:.3f}–{res['jaccard']['max']:.3f}).", "",
          "## 2. New limitation for §8", "",
          "> **Master-list snapshot date.** Package-existence checks depend on a registry",
          "> snapshot. Our original run validated against name lists copied 2026-04-22 (a",
          "> Spracklen-era artifact), not against a snapshot contemporaneous with the",
          "> generation run. Any package registered between the snapshot and the run was",
          "> therefore mis-labelled as hallucinated. v2 re-validates against a",
          f"> {today} snapshot of pypi.org/simple and the npm replica, plus a live HTTP",
          "> check of every candidate name; hallucination is now defined as *absent from the",
          "> fresh list AND not returning HTTP 200 live*. Because registries only grow,",
          "> reported rates are mild over-estimates of the true (snapshot-dependent) rate.", "",
          "## 3. Correction to §9.2", "",
          "- The text stating the master-list snapshots were taken **2026-04-28** is wrong:",
          "  the lists were the Spracklen artifact copied **2026-04-22**, predating the run.",
          "  Replace with the true provenance and the v2 re-snapshot date.",
          "- The claim that a live check was performed should be corrected: in the original",
          "  run `validations.live_status` was empty for every row. v2 populates it for all",
          f"  {sum(sum(d.values()) for d in res['live_status_distribution'].values())} rows.", "",
          "## 4. Figures", "",
          "- Figure 2 (headline rates) and Figure 3 (Jaccard heatmap) are regenerated by the",
          "  same scripts from the recomputed data (`make_figure2.py`, `make_figure3.py`).", ""]

    out = REPO / "reports" / "erratum_draft.md"
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
